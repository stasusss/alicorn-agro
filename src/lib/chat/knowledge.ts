function lines(items: readonly { title: string; text?: string; description?: string }[]) {
  return items
    .map((item) => `- ${item.title}: ${item.text ?? item.description ?? ""}`)
    .join("\n");
}

function section(title: string, body: string) {
  return `# ${title}\n${body.trim()}\n`;
}

